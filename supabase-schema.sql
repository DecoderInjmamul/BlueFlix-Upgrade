-- BlueFlix starter schema.
-- Run only after reviewing it in Supabase SQL Editor.
-- RLS is enabled; public visitors can read published titles.
-- Admin write access is intentionally NOT granted here; configure admin auth
-- and an explicit policy before enabling movie creation/editing.

create table if not exists public.movies (
  id bigint generated by default as identity primary key,
  title text not null,
  release_year integer,
  genre text not null default 'Drama',
  language text,
  overview text,
  poster_url text,
  archive_url text,
  tmdb_id integer unique,
  is_published boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.movies enable row level security;

drop policy if exists "Anyone can read published movies" on public.movies;
create policy "Anyone can read published movies"
on public.movies for select
to anon, authenticated
using (is_published = true);

-- Do not add public INSERT/UPDATE/DELETE policies.
-- Admin permissions must be limited to authenticated admin users.
